/**
 * Turns a CSV of NEW products you ship yourself into catalogue entries (used by `npm run import:products`).
 * Columns (header row required):
 *   id, name, category, price, image, sizes, tags       ← required.  sizes like  S:5|M:10|L:8  (units in stock)
 *   tags (| separated, at least one: they drive the AI stylist)
 *   mrp, brand, images (| separated URLs), colorGroup, explanation, sizeChart, preorder (YYYY-MM-DD)
 * Photos must be images you own; paste their web addresses (https://…).
 */
import { parseCsv } from './csv.js';

const CATS = ['top', 'bottom', 'footwear', 'outerwear', 'set', 'accessory'];
const CHARTS = ['', 'tops', 'bottoms', 'footwear'];
const list = (v) => String(v || '').split('|').map(x => x.trim()).filter(Boolean);
const url = (u) => /^https:\/\/[^\s"'<>]+$/i.test(u);

export function rowsToProducts(text, { existingIds = [] } = {}) {
  const rows = parseCsv(text), errors = [], out = [];
  if (rows.length < 2) return { products: [], errors: ['The file has no rows.'] };
  const head = rows[0].map(h => h.toLowerCase());
  for (const need of ['id', 'name', 'category', 'price', 'image', 'sizes', 'tags']) if (!head.includes(need)) errors.push(`Missing column "${need}".`);
  if (errors.length) return { products: [], errors };
  const seen = new Set(existingIds);
  rows.slice(1).forEach((r, i) => {
    const line = i + 2, g = (n) => (head.includes(n) ? r[head.indexOf(n)] || '' : '');
    const bad = (m) => errors.push(`Line ${line}: ${m}`);
    const id = g('id');
    if (!/^[a-z0-9][a-z0-9-]{2,38}$/.test(id)) return bad('id must be 3-39 lowercase letters, numbers or dashes.');
    if (seen.has(id)) return bad(`id "${id}" is already used.`);
    seen.add(id);
    if (g('name').length < 3 || g('name').length > 80) return bad('name must be 3-80 characters.');
    if (!CATS.includes(g('category'))) return bad(`category must be one of ${CATS.join(', ')}.`);
    if (!/^\d{1,6}$/.test(g('price')) || Number(g('price')) < 1) return bad('price must be a whole number of rupees.');
    if (g('mrp') && (!/^\d{1,6}$/.test(g('mrp')) || Number(g('mrp')) <= Number(g('price')))) return bad('mrp must be a whole number above the price.');
    if (!url(g('image'))) return bad('image must be a full https:// web address.');
    const images = list(g('images')); if (images.some(x => !url(x))) return bad('every address in images must start with https://.');
    const sizes = {};
    for (const part of list(g('sizes'))) {
      const m = /^([A-Za-z0-9.]{1,6}):(\d{1,5})$/.exec(part);
      if (!m) return bad(`sizes must look like S:5|M:10 (got "${part}").`);
      sizes[m[1]] = Number(m[2]);
    }
    if (!Object.keys(sizes).length) return bad('give at least one size.');
    if (!CHARTS.includes(g('sizechart'))) return bad('sizeChart must be tops, bottoms or footwear (or empty).');
    if (g('preorder') && (!/^\d{4}-\d{2}-\d{2}$/.test(g('preorder')) || Number.isNaN(Date.parse(g('preorder'))))) return bad('preorder must be a date like 2027-01-31.');
    if (!list(g('tags')).length) return bad('give at least one tag (for example: streetwear|casual|black). The AI stylist uses tags to build outfits.');
    const p = {
      id, name: g('name'), brand: g('brand') || 'Shonowear', category: g('category'), image: g('image'), images: images.length ? images : [g('image')],
      colorGroup: g('colorgroup') || id, addedAt: new Date().toISOString().slice(0, 10), price: Number(g('price')),
      ...(g('mrp') ? { mrp: Number(g('mrp')) } : {}), fulfilment: 'own', platform: 'Shonowear', sizes,
      ...(g('sizechart') ? { sizeChart: g('sizechart') } : {}), ...(g('preorder') ? { preorder: { shipsOn: g('preorder') } } : {}),
      tags: list(g('tags')), explanation: g('explanation') || `${g('name')} from ${g('brand') || 'Shonowear'}.`,
    };
    out.push(p);
  });
  return { products: errors.length ? [] : out, errors };
}

export function renderModule(products) {
  return `/* GENERATED by \`npm run import:products\` from your CSV. Edit the CSV and run it again; do not edit this file by hand. */\nexport const importedProducts = ${JSON.stringify(products, null, 2)};\n`;
}
